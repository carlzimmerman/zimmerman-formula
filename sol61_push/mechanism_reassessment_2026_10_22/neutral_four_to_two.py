"""Tree-level vacuum 4->2 threshold amplitude in the existing complex action.

All tree topologies are generated by unordered set partitions with the
actual cubic and quartic vertices. No real-mediator substitution is made.
Rates below require a dilute nonrelativistic, incoherent, balanced gas.
"""
from functools import lru_cache
from itertools import combinations
from pathlib import Path
import json
import sys
import math
import numpy as np

m = .001
M = 2*m*math.sqrt(1+.02**2)
g = 2.168e-6
lam = .00881292


@lru_cache(None)
def partitions(items, count):
    if count == 1:
        return ((items,),)
    if len(items)<count:
        return ()
    first, rest = items[0], items[1:]
    out = []
    for size in range(len(rest)+1):
        for chosen in combinations(rest,size):
            left = tuple(i for i in rest if i not in chosen)
            for p in partitions(left,count-1):
                out.append(((first,)+chosen,)+p)
    return tuple(out)


def amplitude(charges, momenta, coupling=g, quartic=lam, root=5):
    """All external momenta incoming; return M up to overall minus sign.

    An off-shell current has charge equal to its external charge sum.
    Each propagator connects conjugate fields, so the parent vertex leg
    has the negative of that current charge. Vertex factors: 2g, 4lambda.
    """
    @lru_cache(None)
    def current(items, amputated=False):
        if len(items)==1:
            return 1.
        q = sum(charges[i] for i in items)
        if abs(q) not in (1,2):
            return 0.
        value = 0.
        for count in [2,3]:
            for groups in partitions(items,count):
                childcharges = [sum(charges[i] for i in group) for group in groups]
                vertex = sorted(childcharges+[-q])
                if vertex in ([-2,1,1],[-1,-1,2]):
                    factor = 2*coupling
                elif vertex == [-1,-1,1,1]:
                    factor = 4*quartic
                else:
                    continue
                value += factor*math.prod(current(group) for group in groups)
        if amputated:
            return value
        p = np.sum(momenta[list(items)],axis=0)
        mass = m if abs(q)==1 else M
        return value/(p[0]**2-np.dot(p[1:],p[1:])-mass**2)
    return current(tuple(i for i in range(6) if i!=root),True)


momenta = np.zeros((6,4))
momenta[:4,0] = m
momenta[4:,0] = -2*m
momenta[4,1] = math.sqrt(3)*m
momenta[5,1] = -math.sqrt(3)*m
channels = {'31':[1,1,1,-1,-1,-1], '22':[1,1,-1,-1,-1,1]}
rows = {}
for name, charges in channels.items():
    values = [amplitude(charges,momenta,root=r) for r in range(6)]
    contact = amplitude(charges,momenta,coupling=0)
    # Every six-point tree has (V3,V4)=(0,2),(2,1),(4,0).
    cubic_only = amplitude(charges,momenta,quartic=0)
    rows[name] = dict(amplitude_GeV_minus2=values[0], roots=values,
        quartic_only=contact, cubic_only=cubic_only,
        mixed=values[0]-contact-cubic_only)

# Integrated two-body phase space at sqrt(s)=4m is beta/(8pi).
# Event rate R31=n+^3 n- |M31|^2 beta /[(2m)^4 8pi 3! 2!].
# Event rate R22=n+^2 n-^2 |M22|^2 beta /[(2m)^4 8pi 2! 2!].
# R13=R31 for n+=n-=n/2. Each event removes two total particles.
phase = (math.sqrt(3)/2)/(8*math.pi)/(2*m)**4
C31 = phase*rows['31']['amplitude_GeV_minus2']**2/12
C22 = phase*rows['22']['amplitude_GeV_minus2']**2/4
C = 2*(2*C31+C22)/16  # dot n+3Hn = -C n^4 when inverse negligible
Ccontact = 45*math.sqrt(3)/(1024*math.pi)*lam**4/m**8

# A survival boundary, not a production prediction: insert target Y and
# ask where the dilute, zero-velocity forward loss rate equals H.
Y = 4.37e-10/m
Mpl = 2.435e18
boundaries=[]
for gstar in [10.75,106.75]:
    scoef = 2*math.pi**2/45*gstar
    hcoef = math.sqrt(math.pi**2*gstar/90)/Mpl
    Tcrit = (hcoef/(C*(Y*scoef)**3))**(1/7)
    boundaries.append(dict(gstar_constant=gstar,Tcrit_visible_GeV=Tcrit,
        density_over_m3=Y*scoef*Tcrit**3/m**3,
        note='Counterfactual target-density cold dilute gas; its phase-space occupancy and actual production temperature are not supplied.'))

# Closed form for forward-only loss with constant g*: Yf/Yi =
# [1+(3/7)(Gamma_i/H_i)]^(-1/3). Inverse reactions/heating excluded.
survival = [{ 'initial_Gamma_over_H':r,
              'Y_final_over_initial':(1+3*r/7)**(-1/3)}
            for r in [0.01,1.,100.,1e6]]
checks = dict(
    root_invariance=all(max(abs(v/r['roots'][0]-1) for v in r['roots'])<1e-10 for r in rows.values()),
    contact_31=abs(rows['31']['quartic_only']/(-18*lam**2/m**2)-1)<1e-12,
    contact_22=abs(rows['22']['quartic_only']/(-12*lam**2/m**2)-1)<1e-12,
    contact_rate=abs((2*(2*phase*rows['31']['quartic_only']**2/12+phase*rows['22']['quartic_only']**2/4)/16)/Ccontact-1)<1e-12,
    momenta_conserved=bool(np.max(np.abs(np.sum(momenta,axis=0)))<1e-15))
out=dict(checks=checks,all_pass=all(checks.values()),channels=rows,
    loss_coefficient_GeV_minus8=C,contact_only_loss_coefficient_GeV_minus8=Ccontact,
    survival_boundaries=boundaries,forward_only_integrated_loss=survival,
    scope='Full tree threshold amplitudes for 31 and 22 neutral-stock loss. Not a finite-temperature average, coherent condensate evolution, all-channel kinetic solution, or surviving cosmological yield. Near-pole propagators need velocity dependence at v comparable to 0.02; no bare on-shell pole is used at threshold.')
Path(sys.argv[1]).write_text(json.dumps(out,indent=2))
print(json.dumps(out,indent=2))
sys.exit(0 if out['all_pass'] else 1)
