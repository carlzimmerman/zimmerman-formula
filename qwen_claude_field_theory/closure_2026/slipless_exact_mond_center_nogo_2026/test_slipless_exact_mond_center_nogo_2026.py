    @unittest.skipIf(core is None, "derivation module not implemented yet")
    def test_physical_curvature_units_cannot_be_silently_set_to_one(self) -> None:
        """Catches mixing physical acceleration with dimensionless metric potentials."""

        n, kappa, a0, b, r, c_light = sp.symbols(
            "n kappa a0 b r c_light", positive=True
        )
        generic = core.derive_generic_center_scaling(
            mu_power=n,
            mu_coefficient=kappa,
            a0=a0,
            b=b,
            radius=r,
            speed_of_light=c_light,
        )
        self.assertEqual(
            sp.simplify(
                generic["Ricci_scalar"].subs(c_light, 2)
                / generic["Ricci_scalar"].subs(c_light, 1)
            ),
            sp.Rational(1, 4),
        )
        self.assertEqual(
            sp.simplify(
                generic["Kretschmann"].subs(c_light, 2)
                / generic["Kretschmann"].subs(c_light, 1)
            ),
            sp.Rational(1, 16),
        )

        s, c_phi, c_psi = sp.symbols("s C_phi C_psi", positive=True)
        slipped = core.derive_arbitrary_slip_center_curvature(
            acceleration_power=s,
            phi_acceleration_coefficient=c_phi,
            psi_acceleration_coefficient=c_psi,
            radius=r,
            speed_of_light=c_light,
        )
        expected_ricci = (
            2 * (s + 2) * (2 * c_psi - c_phi) * r ** (s - 1) / c_light**2
        )
        expected_k = 4 * r ** (2 * s - 2) * (
            c_phi**2 * (s**2 + 2)
            + c_psi**2 * (2 * s**2 + 4 * s + 6)
        ) / c_light**4
        self.assertEqual(sp.simplify(slipped["Ricci_scalar"] - expected_ricci), 0)
        self.assertEqual(sp.simplify(slipped["Kretschmann"] - expected_k), 0)

