    def test_manifest_hashes_pin_every_source_and_output(self) -> None:
        """Catches stale code, report, or result bytes behind a valid schema."""

        here = Path(__file__).resolve().parent
        repository = here.parents[2]
        manifest = json.loads(
            (here / "computation_manifest.json").read_text(encoding="utf-8")
        )
        for item in manifest["sources"] + manifest["outputs"]:
            payload = (repository / item["path"]).read_bytes()
            self.assertEqual(
                hashlib.sha256(payload).hexdigest(),
                item["sha256"],
                item["path"],
            )

