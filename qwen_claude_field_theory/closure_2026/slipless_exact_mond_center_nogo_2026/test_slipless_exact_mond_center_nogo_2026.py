    def test_independent_high_precision_root_audit(self) -> None:
        """Catches a formal series that does not approach the exact implicit root."""

        script = Path(__file__).with_name("independent_numeric_audit.py")
        if not script.exists():
            self.fail("independent numerical root audit is missing")
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / "numeric.json"
            run = subprocess.run(
                [sys.executable, str(script), "--json", "--output", str(output)],
                check=False,
                capture_output=True,
                text=True,
            )
            self.assertEqual(run.returncode, 0, run.stderr or run.stdout)
            result = json.loads(run.stdout)
            self.assertEqual(result, json.loads(output.read_text(encoding="utf-8")))
        self.assertGreater(result["relative_error_log_slope"], 1.49)
        self.assertLess(result["relative_error_log_slope"], 1.51)
        self.assertLess(result["max_equation_residual"], 1e-60)
        self.assertLess(result["scaled_error_limit_deviation"], 5e-6)

