# S_req(x, m) = S_avail(R) with R = rho_d/rho_dm0 and dm_d/dx = C x^2 R
#   C = 4 pi r_M^3 rho_dm0 / M_b
def solve_selfconsistent(a0, Mb, nu0, nstep=60000, vmax=30.0):
    """Integrate in v = -ln(1 - w), w = m_d/(nu(y_b)-1) = fraction of the discrepancy the dust
    has taken over.  w -> 1 IS the wall (S_req -> 0), so the singular endpoint becomes v -> inf
    and the solution converges instead of blowing up.  Baryons treated as a point mass."""
    rM = math.sqrt(G_ * Mb / a0)
    C = 4 * np.pi * rM ** 3 * RHO_DM0 / Mb
    k = 2 * math.sqrt(2) * C / nu0                 # inner branch: m_d = k^2 x^4/16
    def parts(v, x):
        w = 1.0 - math.exp(-v)
        nu = math.sqrt(1 + x * x); D = nu - 1.0; Dp = x / nu; yb = 1.0 / (x * x)
        mm = 1.0 + w * D
        S = min(yb * D * (1 - w) * (nu + mm) / mm, 1.0)   # = [1 + y_b(1-m^2)]/m, stable form
        R = math.sqrt(max((1 + nu0 ** 2) / S ** 4 - 1.0, 0.0)) / nu0
        wp = (C * x * x * R - w * Dp) / D
        return w, mm, S, R, wp
    def dxdv(v, x):
        w, mm, S, R, wp = parts(v, x)
        return (1 - w) / wp
    # start where the inner asymptotic is valid: 8 m_d/x^2 = k^2 x^2/2 must dominate nu0^2
    # (below that the required dust density is just the cosmic mean and the branch does not exist)
    x0 = nu0 * math.sqrt(200.0) / k
    w0 = k ** 2 * x0 ** 2 / 8.0
    v = -math.log(1 - w0); x = x0
    # geometric steps while w << 1 (where x ~ sqrt(w) moves fastest in log), uniform after
    grid = np.concatenate([np.geomspace(v, 0.05, nstep // 4),
                           np.linspace(0.05, vmax, nstep)[1:]])
    V, X = [v], [x]
    for vn in grid[1:]:
        h = vn - v
        a_ = dxdv(v, x); b_ = dxdv(v + h / 2, x + h * a_ / 2)
        c_ = dxdv(v + h / 2, x + h * b_ / 2); d_ = dxdv(v + h, x + h * c_)
        x += h * (a_ + 2 * b_ + 2 * c_ + d_) / 6; v = vn
        V.append(v); X.append(x)
    V, X = np.array(V), np.array(X)
    W = 1 - np.exp(-V)
    NU = np.sqrt(1 + X ** 2)
    MD = W * (NU - 1)                                   # m_d(x)
    RR = np.array([parts(v_, x_)[3] for v_, x_ in zip(V, X)])
