def eta_complement(r):
    """1 - eta, cancellation-free next to the eta = 1 boundary."""
    d = (r * r - 1) ** 2
    if d <= mp.mpf(1) / 16:
        return mp.mpf(0)
    if d >= mp.mpf(1) / 4:
        return mp.mpf(1)
    L = 1 / (mp.mpf(1) / 4 - d) - 1 / (d - mp.mpf(1) / 16)
    t = mp.exp(-abs(L))
    return 1 / (1 + t) if L > 0 else t / (1 + t)


