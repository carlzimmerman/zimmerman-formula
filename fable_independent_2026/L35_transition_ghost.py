def eta_jets(r):
    """(eta, eta', eta'') for the IC5 activation, derived here from E(t) = exp(-1/t)."""
    r = mp.mpf(r)
    d = (r * r - 1) ** 2
    if d <= mp.mpf(1) / 16:
        return mp.mpf(1), mp.mpf(0), mp.mpf(0)
    if d >= mp.mpf(1) / 4:
        return mp.mpf(0), mp.mpf(0), mp.mpf(0)
    left, right = mp.mpf(1) / 4 - d, d - mp.mpf(1) / 16
    L = 1 / left - 1 / right                      # eta = 1/(1+e^L)
    Ld = 1 / left ** 2 + 1 / right ** 2
    Ldd = 2 / left ** 3 - 2 / right ** 3
    dr = 4 * r * (r * r - 1)
    drr = 12 * r * r - 4
    L1 = Ld * dr
    L2 = Ldd * dr ** 2 + Ld * drr
    t = mp.exp(-abs(L))
    if L > 0:
        e, cm = t / (1 + t), 1 / (1 + t)
    else:
        e, cm = 1 / (1 + t), t / (1 + t)
    prod = t / (1 + t) ** 2                       # = eta (1-eta), cancellation-free
    return e, -prod * L1, prod * ((cm - e) * L1 * L1 - L2)


