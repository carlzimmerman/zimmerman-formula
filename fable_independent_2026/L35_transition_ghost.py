            t = min(max(t, mp.mpf(0)), mp.mpf(1))
            if kind == "smoothstep":
                return 3 * t ** 2 - 2 * t ** 3
            if kind == "smootherstep":
                return 6 * t ** 5 - 15 * t ** 4 + 10 * t ** 3
            if kind == "raised cosine":
                return (1 - mp.cos(mp.pi * t)) / 2
            if kind == "skewed (t^3 warp)":
                s = t ** 3
                return 3 * s ** 2 - 2 * s ** 3
