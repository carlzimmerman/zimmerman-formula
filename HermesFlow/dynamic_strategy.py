class DynamicHermesExplorer:
    """
    The next-generation HermesFlow that reasons instead of pattern-matches.

    Flow:
    1. Analyze topic → Generate TopicProfile
    2. Plan search → Generate SearchStrategies
    3. Execute with validation → DynamicValidator
    4. Learn from outcomes → OutcomeTracker
    """

    def __init__(self, verbose: bool = True, z2_context: str = None):
        self.verbose = verbose
        self.z2_context = z2_context or self._default_z2_context()

        self.analyzer = TopicAnalyzer(verbose)
        self.planner = StrategyPlanner(verbose)
        self.validator = DynamicValidator(verbose)
        self.tracker = OutcomeTracker()

    def _default_z2_context(self) -> str:
        """Default Z² framework context for predictions."""
        import math
        Z2 = 32 * math.pi / 3
        Z = math.sqrt(Z2)
        PHI = (1 + math.sqrt(5)) / 2

        return f"""
Z² = 32π/3 = {Z2:.6f}
Z = √(Z²) = {Z:.6f}
φ = (1+√5)/2 = {PHI:.6f}

Key predictions:
- Coefficients of variation often ≈ Z or Z²/10
- Ratios between quantities often ≈ φ or 1/φ
- Scale transitions occur at Z² boundaries
"""

    def _log(self, msg: str):
        if self.verbose:
            print(f"[DynamicHermes] {msg}")

    def explore(self, topic: str, domain: str) -> Dict:
        """
        Full dynamic exploration for any topic.

        This is the main entry point - give it ANY topic and it will:
        1. Figure out what to search for
        2. Generate search strategies
        3. Execute and validate
        4. Learn from outcomes
        """
        self._log(f"=" * 60)
        self._log(f"DYNAMIC EXPLORATION: {topic}")
        self._log(f"Domain: {domain}")
        self._log(f"=" * 60)

        # Phase 1: Understand the topic
        self._log("\n--- Phase 1: Topic Analysis ---")
        profile = self.analyzer.analyze(topic, domain, self.z2_context)

        self._log(f"Key terms: {profile.key_terms}")
        self._log(f"Sources: {[s.get('name') for s in profile.authoritative_sources]}")
        self._log(f"Quantities: {profile.target_quantities}")

        # Check for learned hints
        hints = self.tracker.get_domain_hints(domain)
        if hints.get("successful_sources"):
            self._log(f"Learned sources for {domain}: {hints['successful_sources']}")
            # Could boost these in search

        # Phase 2: Plan search strategies
        self._log("\n--- Phase 2: Strategy Planning ---")
        strategies = self.planner.plan(profile)

        for i, s in enumerate(strategies[:3]):
            self._log(f"Strategy {i+1}: {s.query[:50]}...")
            self._log(f"  Rationale: {s.rationale[:50]}...")

        # Phase 3: Execute (would integrate with actual HermesExplorer)
        self._log("\n--- Phase 3: Execution ---")
        self._log("(Would execute search strategies here)")

        # Return the dynamic profile and strategies for integration
        return {
            "profile": asdict(profile),
            "strategies": [asdict(s) for s in strategies],
            "domain_hints": hints
        }


