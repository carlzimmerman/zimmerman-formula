def compute_bayes_factor(C_obs, sigma, gamma_ratio, prior_width=0.1):
    """
    Compute Bayes factor for Z² vs GR given observed cross-correlation.

    Parameters:
    -----------
    C_obs : float
        Observed cross-correlation (normalized to Ω_GW units)
    sigma : float
        Measurement uncertainty
    gamma_ratio : float
        Ratio γ_standard / γ_++ (the null test ratio)
    prior_width : float
        Width of prior on Ω (relative to sigma)

    Returns:
    --------
    B : float
        Bayes factor P(data|H_Z2) / P(data|H_GR)
    """
    # For GR hypothesis: signal appears with amplitude Ω × γ_standard
    # For Z² hypothesis: signal appears with amplitude Ω × γ_++
    # If true signal is h+ only with amplitude Ω_true:
    #   - GR estimator gives: Ĉ_GR = Ω_true × (γ_++ / γ_standard) = Ω_true / R
    #   - Z² estimator gives: Ĉ_Z2 = Ω_true

    # The key is: what Ω does each model infer from C_obs?
    # GR model infers: Ω_GR = C_obs / γ_standard (uses wrong ORF)
    # Z² model infers: Ω_Z2 = C_obs / γ_++ = C_obs × R (uses correct ORF)

    # Likelihood for GR (assuming C_obs was generated by unpolarized source)
    # P(C_obs | Ω, GR) ∝ exp[-1/2 × (C_obs - Ω)² / σ²]

    # Likelihood for Z² (assuming C_obs was generated by h+ only source)
    # The observed C in standard analysis is biased low by factor R
    # P(C_obs | Ω, Z2) ∝ exp[-1/2 × (C_obs - Ω/R)² / σ²]

    # With flat priors on Ω:
    # Evidence_GR = ∫ exp[-1/2 × (C_obs - Ω)² / σ²] dΩ ∝ σ
    # Evidence_Z2 = ∫ exp[-1/2 × (C_obs × R - Ω)² / (σR)²] dΩ ∝ σR

    # For a detection (C_obs >> σ), the ratio depends on which model fits better

    # Simple case: evaluate likelihood ratio at best-fit Ω
    # GR best fit: Ω = C_obs
    # Z² best fit: Ω = C_obs × gamma_ratio

    # If C_obs is consistent with noise (|C_obs| < 2σ), both models are OK
    # If C_obs is positive (detection), Z² fits if C_obs × R is reasonable

    # The key discriminant is the ratio of inferred amplitudes
    R = gamma_ratio

    # Log Bayes factor (approximate for Gaussian case)
    # If true signal is h+ only:
    #   - Standard search sees: Ω_apparent = Ω_true / R
    #   - Polarized search sees: Ω_apparent = Ω_true
    # The ratio should be R if h+ only, 1 if unpolarized

    # For current data (upper limits only), we use the ratio of upper limits
    # This is a crude approximation

    if C_obs < 0:
        # No detection - both models equally consistent with noise
        log_B = 0
    else:
        # Positive correlation - check consistency
        # Under Z²: expect C_obs/σ ~ Ω_true/(σ×R)
        # Under GR: expect C_obs/σ ~ Ω_true/σ

        # Likelihood ratio at best fit
        chi2_GR = (C_obs / sigma)**2 / 2
        chi2_Z2 = (C_obs * R / (sigma * R))**2 / 2  # = chi2_GR (same for detection)

        # The difference comes from prior volume
        # Z² has tighter prior (predicts specific r), GR has wide prior
        # This actually PENALIZES Z² by Occam factor

        # For fair comparison, use same prior width
        log_B = 0  # Models are equivalent for non-detection

    return np.exp(log_B)


