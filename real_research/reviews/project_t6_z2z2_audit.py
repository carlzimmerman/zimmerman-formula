import numpy as np

G = {'1': (1, 1, 1), 'theta': (1, -1, -1), 'omega': (-1, 1, -1), 'theta*omega': (-1, -1, 1)}


def chi_common(g, h):
    """chi of the common fixed locus of commuting g,h: a coord is point-fixed if EITHER flips it; else free T^2."""
    chi = 1
    for a, b in zip(G[g], G[h]):
        chi *= 4 if (a < 0 or b < 0) else 0     # 4 two-torsion points (chi=4) vs free T^2 (chi=0)
    return chi


