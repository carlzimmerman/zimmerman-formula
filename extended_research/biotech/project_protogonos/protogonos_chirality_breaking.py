import numpy as np
import matplotlib.pyplot as plt
import json
import os

# Z² Constants
Z_SQUARED = 32 * np.pi / 3
Z_CONSTANT = 2 * np.sqrt(8 * np.pi / 3)
THETA_Z = np.pi / Z_CONSTANT  # ~31.09 degrees

class ChiralityBreakingModel:
    def __init__(self):
        # 5D Kaluza-Klein parity violation coupling strength
        # The compactification sign ambiguity R5 = ±R50 biases the potential
        self.epsilon_pv = 1e-14  # Weak force parity violation is ~1e-17, KK topology is stronger
        
        # Z² preferred backbone angles (L-amino acids)
        self.phi_L = -(11/6) * THETA_Z * (180/np.pi)  # ~-57 deg
        self.psi_L = -(9/6) * THETA_Z * (180/np.pi)   # ~-47 deg
        
        # Anti-Z² preferred backbone angles (D-amino acids)
        self.phi_D = -self.phi_L
        self.psi_D = -self.psi_L

    def delta_g_chiral_bias(self, temperature_K: float) -> float:
        """
        Calculate the energetic advantage of L-amino acids at Z² angles.
        This is not a thermodynamic standard state difference, but a kinetic/geometric
        selection advantage during polymerization on a Z²-compliant surface.
        """
        # Base geometric matching bonus (kJ/mol)
        base_advantage = 0.05 
        
        # Entropic penalty reduction at lower temperatures
        temp_factor = 298.15 / temperature_K
        
        return base_advantage * temp_factor

    def simulate_frank_amplification(self, initial_ee: float, generations: int, temperature_K: float):
        """
        Simulate the Frank autocatalytic model with Z² geometric bias.
        L + L -> LL (catalyzes L)
        D + D -> DD (catalyzes D)
        L + D -> LD (mutual antagonism / dead end)
        """
        # Concentrations
        L = 0.5 + (initial_ee / 2)
        D = 0.5 - (initial_ee / 2)
        
        history_ee = [initial_ee]
        
        # Z² bias increases the reaction rate constant for L+L vs D+D
        bias_energy = self.delta_g_chiral_bias(temperature_K)
        # R = 8.314 J/molK = 0.008314 kJ/molK
        R = 0.008314
        k_L_bonus = np.exp(bias_energy / (R * temperature_K))
        
        k_L = 1.0 * k_L_bonus
        k_D = 1.0 
        k_LD = 1.5  # Mutual antagonism rate (needs to be high for bistability)
        
        dt = 0.01
        
        for _ in range(generations):
            # Production
            prod_L = k_L * L * L
            prod_D = k_D * D * D
            
            # Annihilation (LD complex formation)
            annihilation = k_LD * L * D
            
            # Update (normalized to maintain total concentration pool = 1)
            dL = (prod_L - annihilation) * dt
            dD = (prod_D - annihilation) * dt
            
            L += dL
            D += dD
            
            total = L + D
            if total > 0:
                L /= total
                D /= total
            
            ee = L - D
            history_ee.append(ee)
            
            if ee >= 0.9999 or ee <= -0.9999:
                break
                
        return history_ee

def run_phase2_analysis():
    print("="*60)
    print("PROJECT PROTOGONOS: Phase 2 - Chirality Breaking")
    print("Z² Geometry Autocatalytic Amplification")
    print("="*60)
    
    model = ChiralityBreakingModel()
    
    # 1. Energy Difference
    temp_K = 350.0  # Warm prebiotic pool
    dg_bias = model.delta_g_chiral_bias(temp_K)
    print(f"\n[1] Z² Geometric Bias at {temp_K} K:")
    print(f"  L-amino acid energetic advantage: {dg_bias:.5f} kJ/mol")
    
    # 2. Simulation
    print("\n[2] Autocatalytic Amplification Simulation:")
    # Start with pure parity violation (1e-17) or meteorite excess (1e-2)
    scenarios = {
        "Weak Force Parity Violation": 1e-17,
        "Meteoritic Excess": 0.02
    }
    
    results_list = []
    
    for name, init_ee in scenarios.items():
        print(f"  Simulating: {name} (Initial ee: {init_ee:.1e})")
        
        history = model.simulate_frank_amplification(init_ee, 500000, temp_K)
        final_ee = history[-1]
        gens = len(history)
        
        print(f"    Final ee: {final_ee:.4f} after {gens} steps")
        results_list.append({
            "scenario": name,
            "initial_ee": init_ee,
            "final_ee": final_ee,
            "generations": gens
        })
        
    # Save results
    os.makedirs("results", exist_ok=True)
    out_file = "results/phase2_chirality.json"
    with open(out_file, 'w') as f:
        json.dump(results_list, f, indent=2)
        
    print(f"\nResults saved to {out_file}")
    print("="*60)

if __name__ == "__main__":
    run_phase2_analysis()
