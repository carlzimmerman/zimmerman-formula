"""AT1: sample-level decision rule for a0 tracking rho_DE vs a0 ~ H(z), and its core-Lean certificate.

Reads CFG689's primary posterior quantiles (BAO+SN.P1), reproduces e_3sigma on CFG683's grid, writes the Lean
certificate with integers generated here (micro-dex, conservative rounding per claim), compiles it, and reports.
Frozen criteria: FROZEN_CRITERIA.md (2d68f8e546). Grades no data. kappa = 1/2 FITTED; not theory closed.

Run from the repo root:  python3 rebuild_2026_10_22/AT1_a0z_tracking_decision/at1.py      (MUTATE=1 for the control)
"""
import json, math, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(ROOT, "campaign_fresh_gravity", "CFG689_native_ruler_bao", "cfg689.json")
MUTATE = os.environ.get("MUTATE") == "1"
SUFFIX = "_MUTATE" if MUTATE else ""
ZS = ["1.0", "1.2", "1.5", "2.33"]
U = 10**6                                   # micro-dex
GRID = [0.01 + k * 0.99 / 999 for k in range(1000)]   # CFG683 grid, 0.01-1.0, 1000 points
S_LIST = [0.14, 0.20, 0.30]                 # per-galaxy error (dex), section 4 C2
C_LIST = [0.05, 0.075]                      # declared common mode (dex), section 4 C2

checks = []


def check(name, ok, detail):
    checks.append((name, bool(ok), detail))


def up(x):
    return math.ceil(x * U - 1e-9)


def dn(x):
    return math.floor(x * U + 1e-9)


def isqrt_up(n):
    r = math.isqrt(n)
    return r if r * r >= n else r + 1


p1 = json.load(open(SRC))["BAO+SN"]["P1"]
rows = {}
for z in ZS:
    q = p1[z]
    X = q["sqrtX_q"]; E = q["E_q"]
    gap = math.log10(E[1]) - math.log10(X[3])
    sE = math.log10(E[2]) - math.log10(E[1])
    sX = math.log10(X[3]) - math.log10(X[2])
    if MUTATE:
        sX *= 2.0
    S = lambda e: gap / math.sqrt(e * e + sE * sE + sX * sX)
    passing = [e for e in GRID if S(e) >= 3]
    e3 = max(passing) if passing else None
    rows[z] = dict(gap=gap, sE=sE, sX=sX, e3=e3, e3_cfg689=q["e_3sigma"])
    if not MUTATE:
        check(f"K1 e_3sigma z {z}", e3 is not None and abs(e3 - q["e_3sigma"]) <= 0.001,
              f"AT1 {e3} vs CFG689 {q['e_3sigma']}")

# ---- Lean generation -------------------------------------------------------------------------------------------
L = ["/-! AT1 certificate (generated by at1.py; integers are micro-dex from cfg689.json BAO+SN.P1; core Lean only).",
     f"   MUTATE = {MUTATE}. Each claim uses conservative rounding for its direction. -/", ""]
names = []
c3_fail = []
lean_rows = {}
for z in ZS:
    r = rows[z]; tag = z.replace(".", "_")
    if r["e3"] is None:
        # nothing passes: certify that even e = 0 gives S < 3 with gap rounded up, widths down
        g = up(r["gap"]); se = dn(r["sE"]); sx = dn(r["sX"])
        L.append(f"-- z {z}: no e on the grid reaches S >= 3")
        L.append(f"theorem c1_none_z{tag} : ({g}:Int)*{g} < 9*({se}*{se} + {sx}*{sx}) := by decide")
        names.append(f"c1_none_z{tag}")
        lean_rows[z] = dict(e3_micro=None)
        continue
    # C1a: S(e3) >= 3 : gap down, widths up, e up
    g = dn(r["gap"]); se = up(r["sE"]); sx = up(r["sX"]); e = up(r["e3"])
    L.append(f"-- z {z}: gap {r['gap']:.6f}, sig_E {r['sE']:.6f}, sig_X {r['sX']:.6f}, e_3sigma {r['e3']:.6f}")
    L.append(f"theorem c1a_z{tag} : 9*(({e}:Int)*{e} + {se}*{se} + {sx}*{sx}) ≤ {g}*{g} := by decide")
    # C1b: S(e3 + 0.001) < 3 : gap up, widths down, e down
    g2 = up(r["gap"]); se2 = dn(r["sE"]); sx2 = dn(r["sX"]); e2 = dn(r["e3"]) + 1000
    L.append(f"theorem c1b_z{tag} : ({g2}:Int)*{g2} < 9*({e2}*{e2} + {se2}*{se2} + {sx2}*{sx2}) := by decide")
    names += [f"c1a_z{tag}", f"c1b_z{tag}"]
    # C3: 2(A + B) <= gap with A >= sqrt(e^2 + sX^2), B >= sqrt(e^2 + sE^2)
    A = isqrt_up(e * e + sx * sx); B = isqrt_up(e * e + se * se)
    if 2 * (A + B) <= g:
        L.append(f"theorem c3_z{tag} : ({e}:Int)*{e} + {sx}*{sx} ≤ {A}*{A} ∧ ({e}:Int)*{e} + {se}*{se} ≤ {B}*{B} "
                 f"∧ 2*(({A}:Int) + {B}) ≤ {g} := by decide")
        names.append(f"c3_z{tag}")
    else:
        # certify the failure instead: lower bounds on the roots already exceed the gap
        Al = math.isqrt(dn(r["e3"]) ** 2 + dn(r["sX"]) ** 2); Bl = math.isqrt(dn(r["e3"]) ** 2 + dn(r["sE"]) ** 2)
        g3 = up(r["gap"])
        L.append(f"-- C3 FAILS at z {z}: 2-sigma zones of both laws overlap at e = e_3sigma")
        L.append(f"theorem c3_fails_z{tag} : ({Al}:Int)*{Al} ≤ {dn(r['e3'])}*{dn(r['e3'])} + {dn(r['sX'])}*{dn(r['sX'])} "
                 f"∧ ({Bl}:Int)*{Bl} ≤ {dn(r['e3'])}*{dn(r['e3'])} + {dn(r['sE'])}*{dn(r['sE'])} "
                 f"∧ {g3} < 2*(({Al}:Int) + {Bl}) := by decide")
        names.append(f"c3_fails_z{tag}")
        c3_fail.append(z)
    # C2: N_min table, e3 floored (one integer used for both directions)
    e3f = dn(r["e3"]); nmin = {}
    for s in S_LIST:
        for c in C_LIST:
            si = round(s * U); ci = round(c * U)
            room = e3f * e3f - ci * ci
            key = f"s{s}_c{c}"
            if room <= 0:
                L.append(f"theorem c2_blocked_z{tag}_{key.replace('.', 'p')} : ({e3f}:Int)*{e3f} ≤ {ci}*{ci} := by decide")
                names.append(f"c2_blocked_z{tag}_{key.replace('.', 'p')}")
                nmin[key] = None
                continue
            n = -(-(si * si) // room)
            nm = f"c2_nmin_z{tag}_{key.replace('.', 'p')}"
            L.append(f"theorem {nm} : ({si}:Int)*{si} ≤ {n}*(({e3f}:Int)*{e3f} - {ci}*{ci}) ∧ "
                     f"¬ (({si}:Int)*{si} ≤ {n - 1}*(({e3f}:Int)*{e3f} - {ci}*{ci})) := by decide")
            names.append(nm)
            nmin[key] = n
    lean_rows[z] = dict(e3_micro=e3f, nmin=nmin, c_ceiling_dex=e3f / U)
    L.append("")

# C2 general theorem: a common mode above e_3sigma blocks the gate for any statistical error
L += ["theorem c2_general (e3 c es : Nat) (h : e3 < c) : ¬ (es*es + c*c ≤ e3*e3) := by",
      "  have h2 : e3*e3 < c*c := Nat.mul_self_lt_mul_self h",
      "  omega", ""]
names.append("c2_general")
# C4: the four outcome conditions are pairwise disjoint (so the check order does not matter); d in milli-sigma
L += ["def trackingC (dT dR : Int) : Prop := -2000 ≤ dT ∧ dT ≤ 2000 ∧ 3000 ≤ dR",
      "def rivalC (dT dR : Int) : Prop := -2000 ≤ dR ∧ dR ≤ 2000 ∧ 3000 ≤ dT",
      "def neitherC (dT dR : Int) : Prop := (dT < -3000 ∨ 3000 < dT) ∧ (dR < -3000 ∨ 3000 < dR)",
      "theorem c4_tr (dT dR : Int) : ¬ (trackingC dT dR ∧ rivalC dT dR) := by",
      "  unfold trackingC rivalC; omega",
      "theorem c4_tn (dT dR : Int) : ¬ (trackingC dT dR ∧ neitherC dT dR) := by",
      "  unfold trackingC neitherC; omega",
      "theorem c4_rn (dT dR : Int) : ¬ (rivalC dT dR ∧ neitherC dT dR) := by",
      "  unfold rivalC neitherC; omega", ""]
names += ["c4_tr", "c4_tn", "c4_rn"]
L += [f"#print axioms {n}" for n in names]
lean_src = "\n".join(L) + "\n"

# K3: no footing a0 or measured kappa in the generated Lean or this script's numeric literals
code = open(__file__).read()
bad = [p for p in ["9.36", "1.13e-10", "1.1312", "9.3603", "1.2e-10", "0.417", "0.450"] if p in lean_src
       or re.search(r"(?<![\w\"'])" + re.escape(p) + r"(?![\w\"'])", code.split("bad = [")[0])]
check("K3 no footing a0 / measured kappa", not bad, f"hits {bad}")

lean_path = os.path.join(HERE, f"AT1_cert{SUFFIX}.lean")
open(lean_path, "w").write(lean_src)
proc = subprocess.run(["lean", lean_path], capture_output=True, text=True, timeout=600)
lean_out = (proc.stdout + proc.stderr).strip()
ax_ok = proc.returncode == 0 and "sorry" not in lean_out and all(
    ("does not depend on any axioms" in ln) or ("[propext]" in ln) or ("[propext, Quot.sound]" in ln)
    or ("[Quot.sound]" in ln) for ln in lean_out.splitlines() if "depend" in ln)
n_ax = sum("depend" in ln for ln in lean_out.splitlines())
check("K2 Lean certificate compiles, no sorry, core axioms only", ax_ok and n_ax == len(names),
      f"rc {proc.returncode}, {n_ax}/{len(names)} axiom lines")

if MUTATE:
    fell = [z for z in ZS if rows[z]["e3"] is None or rows[z]["e3"] < json.load(open(SRC))["BAO+SN"]["P1"][z]["e_3sigma"]]
    check("M1 sigma_X doubled: e_3sigma falls at all four z", len(fell) == 4, f"fell at {fell}")
    check("M2 z 2.33 becomes NOT DECIDABLE", rows["2.33"]["e3"] is None, f"e3 {rows['2.33']['e3']}")
    # frozen section 6: C1 stated with the mutated widths at the unmutated e_3sigma must fail to compile at z 2.33
    r = rows["2.33"]; e0 = up(json.load(open(SRC))["BAO+SN"]["P1"]["2.33"]["e_3sigma"])
    g, se, sx = dn(r["gap"]), up(r["sE"]), up(r["sX"])
    bite = os.path.join(HERE, "AT1_cert_MUTATE_c1a_z2_33.lean")
    open(bite, "w").write("-- MUTATE bite: C1a at z 2.33 with sigma_X doubled and the unmutated e_3sigma; must NOT compile\n"
                          f"theorem c1a_mut_z2_33 : 9*(({e0}:Int)*{e0} + {se}*{se} + {sx}*{sx}) ≤ {g}*{g} := by decide\n")
    pb = subprocess.run(["lean", os.path.basename(bite)], capture_output=True, text=True, timeout=600, cwd=HERE)
    check("M3 Lean C1a at z 2.33 fails to compile under the mutation", pb.returncode != 0,
          f"rc {pb.returncode}: {(pb.stdout + pb.stderr).strip().splitlines()[0][:160] if (pb.stdout + pb.stderr).strip() else ''}")

# ---- report ----------------------------------------------------------------------------------------------------
out = [f"AT1 a0(z) tracking decision rule, MUTATE={MUTATE}. Source cfg689.json BAO+SN.P1 (CFG689 primary).",
       "kappa = 1/2 FITTED; not theory closed. Grades no data.", "",
       "z     gap(dex)  sig_E    sig_X    e_3sig(AT1)  e_3sig(CFG689)  common-mode ceiling c < e_3sig"]
for z in ZS:
    r = rows[z]
    out.append(f"{z:<5} {r['gap']:.4f}   {r['sE']:.4f}   {r['sX']:.4f}   "
               f"{('%.4f' % r['e3']) if r['e3'] else 'none':<12} {r['e3_cfg689']:.4f}          "
               f"{('%.4f' % r['e3']) if r['e3'] else 'NOT DECIDABLE'}")
out += ["", "N_min (z-sample galaxies, reference sample error taken as zero; e_3sigma floored to 1e-6 dex):"]
for z in ZS:
    nm = lean_rows[z].get("nmin")
    if nm:
        out.append(f"  z {z}: " + ", ".join(f"{k}: {'blocked' if v is None else v}" for k, v in nm.items()))
out += ["", f"C3 (no double 2-sigma consistency at e_3sigma): FAILS at {c3_fail if c3_fail else 'none'}"
        + ("; a sample at e_3sigma can land INCONCLUSIVE there (rule stays exclusive by C4)" if c3_fail else ""), ""]
out += ["Lean (" + os.path.basename(lean_path) + "):", lean_out, ""]
for n, ok, d in checks:
    out.append(f"[{'PASS' if ok else 'FAIL'}] {n}: {d}")
fail = [n for n, ok, _ in checks if not ok]
out.append(f"RESULT: {len(checks) - len(fail)}/{len(checks)} checks pass" + (f"; FAIL {fail}" if fail else ""))
print("\n".join(out))
json.dump(dict(mutate=MUTATE, rows=rows, lean=lean_rows, c3_fail=c3_fail,
               checks=[dict(name=n, ok=ok, detail=d) for n, ok, d in checks]),
          open(os.path.join(HERE, f"at1{SUFFIX}.json"), "w"), indent=1, default=str)
sys.exit(1 if fail else 0)
