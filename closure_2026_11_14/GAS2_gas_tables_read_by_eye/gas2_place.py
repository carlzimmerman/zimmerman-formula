def tau_rows(symmetrise):
    rows = []
    for lab, z, f, p, m in FLUX:
        t = -math.log(f)
        hi, lo = -math.log(f - m), -math.log(f + p)  # tau interval from the flux interval
        if symmetrise:
            h = 0.5 * (hi - lo)
            rows.append((lab, z, t, h, h))
        else:
            rows.append((lab, z, t, hi - t, t - lo))
    return rows + TAU_DIRECT


def tau_rec(z):
    return 0.751 * ((1 + z) / 4.5) ** 2.90 - 0.132


def level(val_of_z, rows, za):
    """Best level and the papers giving it. val_of_z(z) gives the bracket value at a measurement's redshift."""
    one, two = set(), set()
    for lab, z, c, p, m in rows:
        if abs(z - za) > WIN:
            continue
        v = val_of_z(z)
        if c - m <= v <= c + p:
            one.add(lab)
        elif c - 2 * m <= v <= c + 2 * p:
            two.add(lab)
    if one:
        return "INSIDE 1 SIGMA (" + ", ".join(sorted(one)) + ")"
    if two:
        return "INSIDE 2 SIGMA (" + ", ".join(sorted(two)) + ")"
    return "OUTSIDE"


def table(title, brackets, rows):
    print(f"\n## {title}\n")
    print("| bracket | " + " | ".join(f"z {a}" for a in ANCH) + " |")
    print("|---|" + "---|" * len(ANCH))
    for name, fn in brackets:
        cells = [level(lambda z, a=a: fn(z, a), rows, a) for a in ANCH]
        print(f"| {name} | " + " | ".join(cells) + " |")


