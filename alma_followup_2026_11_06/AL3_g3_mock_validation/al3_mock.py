"""AL3 MOCK cube writer: a copy of cfg942_common.write_mock_cube plus a clump (sp["clump"]) and AR(1) channel noise (sp["rho_ch"]).
The line offset is set through sp["nu_line"] (as AL1). With both options absent the output must equal the frozen writer's (K0).
MOCK cubes, NOT ALMA DATA. kappa = 1/2 FITTED; not theory closed."""
import math, os
import numpy as np
from scipy import special


def clump_model(cl, p, X, Y, v, dv, inc, kpa, kf, Xn, Yn, bp, dtype=np.float32):
    """Gaussian clump in the disc plane (sigma, centre radius in arcsec; azimuth from the receding major axis), moving with the disc's
    line-of-sight velocity field of p, channel-integrated Gaussian line of width p[6], beam-convolved. Flux cl["SdV"] Jy km/s."""
    from scipy import fft as sfft
    x0, y0, pa, vsys, vf, rt, s0, _, h = p
    c, s = math.cos(pa), math.sin(pa); ci, si = math.cos(math.radians(inc)), math.sin(math.radians(inc))
    def plane(XX, YY):
        xr = (XX - x0) * c + (YY - y0) * s; yr = -(XX - x0) * s + (YY - y0) * c; return xr, yr / ci
    az = math.radians(cl["az_deg"]); cx, cy = cl["r_as"] * math.cos(az), cl["r_as"] * math.sin(az)
    xd, yd = plane(Xn, Yn); A = cl["SdV"] * bp / np.exp(-((xd - cx) ** 2 + (yd - cy) ** 2) / (2 * cl["sig_as"] ** 2)).sum()
    xd, yd = plane(X, Y); R = np.hypot(xd, yd); cth = xd / np.maximum(R, 1e-9)
    Vlos = vsys + vf * (2 / math.pi) * np.arctan(R * kpa / rt) * si * cth
    I = A * np.exp(-((xd - cx) ** 2 + (yd - cy) ** 2) / (2 * cl["sig_as"] ** 2)) / dv
    w = 1.0 / (math.sqrt(2) * s0); cube = np.empty((len(v),) + X.shape, np.float64)
    for i, vk in enumerate(v):
        a = (vk - dv / 2 - Vlos) * w; cube[i] = 0.5 * (special.erf(a + dv * w) - special.erf(a)) * I
    kf64 = kf.astype(np.complex128)
    return sfft.irfft2(sfft.rfft2(cube, axes=(1, 2), workers=1) * kf64[None], s=X.shape, axes=(1, 2), workers=1).astype(dtype)


def write_mock_cube(C, path, sp):
    """cfg942_common.write_mock_cube, copied line for line; the two AL3 options are the only additions (marked AL3)."""
    from astropy.io import fits
    rng = np.random.default_rng(sp["seed"]); n = sp["n"]; pix = sp["pix"]
    v = np.arange(sp["vlo"], sp["vhi"] + 1e-6, sp["dv"]); nch = len(v)
    yy, xx = np.indices((n, n)); X, Y = (xx - n // 2) * pix, (yy - n // 2) * pix
    bp = C.beam_pix(sp["beam"], pix); kf = C.kernel_rfft((n, n), sp["beam"], pix)
    kn = C.kernel_rfft((n, n), (sp["beam"][0] / math.sqrt(2), sp["beam"][1] / math.sqrt(2), sp["beam"][2]), pix)   # noise autocorrelation = beam
    msub = min(n, 2 * int(math.ceil((10 * sp["h"] + 4 * sp["beam"][0]) / pix)) + 1); a0 = n // 2 - msub // 2
    Xs, Ys = X[a0:a0 + msub, a0:a0 + msub], Y[a0:a0 + msub, a0:a0 + msub]; kfs = C.kernel_rfft((msub, msub), sp["beam"], pix, np.float32)
    cl = sp.get("clump"); fdisc = 1.0 - (cl["frac"] if cl else 0.0)          # AL3
    if sp["SdV"] > 0:
        c, s = math.cos(sp["pa"]), math.sin(sp["pa"]); xr = X * c + Y * s; yr = -X * s + Y * c
        I0 = (sp["SdV"] * fdisc if cl else sp["SdV"]) * bp / np.exp(-np.sqrt(xr ** 2 + (yr / sp["q_int"]) ** 2) / sp["h"]).sum()
        p = [0.0, 0.0, sp["pa"], 0.0, sp["vf"], sp["rt"], sp["s0"], I0, sp["h"]]
    nu = sp["nu_line"] * (1 - v / C.CKMS)
    h = fits.Header()
    h["SIMPLE"] = True; h["BITPIX"] = -32; h["NAXIS"] = 3; h["NAXIS1"] = n; h["NAXIS2"] = n; h["NAXIS3"] = nch
    h["OBJECT"] = "MOCK"; h["COMMENT"] = "MOCK cube generated by the CFG942 harness. NOT ALMA DATA."; h["MOCKLAB"] = sp["label"]
    h["BUNIT"] = "Jy/beam"; h["CTYPE1"] = "RA---SIN"; h["CTYPE2"] = "DEC--SIN"; h["CUNIT1"] = h["CUNIT2"] = "deg"
    h["CRVAL1"], h["CRVAL2"] = sp["ra"], sp["dec"]; h["CRPIX1"] = h["CRPIX2"] = n // 2 + 1
    h["CDELT1"], h["CDELT2"] = -pix / 3600.0, pix / 3600.0
    h["CTYPE3"] = "FREQ"; h["CUNIT3"] = "Hz"; h["CRVAL3"] = nu[0] * 1e9; h["CRPIX3"] = 1.0; h["CDELT3"] = (nu[1] - nu[0]) * 1e9
    h["SPECSYS"] = "LSRK"; h["RESTFRQ"] = sp["restfrq"] * 1e9
    h["BMAJ"], h["BMIN"], h["BPA"] = sp["beam"][0] / 3600.0, sp["beam"][1] / 3600.0, sp["beam"][2]
    for k, val in sp.get("true", {}).items(): h["HIERARCH MOCK " + k] = val
    if os.path.exists(path): os.remove(path)
    rho = float(sp.get("rho_ch", 0.0)); prev = None                           # AL3
    sh = fits.StreamingHDU(path, h)
    for j0 in range(0, nch, 4):
        vv = v[j0:j0 + 4]; blk = np.zeros((len(vv), n, n), np.float32)
        if sp["SdV"] > 0 and np.any(np.abs(vv) <= 900):
            blk[:, a0:a0 + msub, a0:a0 + msub] += C.disc_model(p, Xs, Ys, vv, sp["dv"], sp["inc"], sp["kpa"], kfs, q_int=sp["q_int"], dtype=np.float32) * (np.abs(vv) <= 900)[:, None, None]
            if cl:                                                             # AL3: the cube's own velocity frame has the line at 0
                blk[:, a0:a0 + msub, a0:a0 + msub] += clump_model(dict(cl, SdV=sp["SdV"] * cl["frac"]), p, Xs, Ys, vv, sp["dv"], sp["inc"], sp["kpa"], kfs, X, Y, bp) * (np.abs(vv) <= 900)[:, None, None]
        for i in range(len(vv)):
            nz = np.fft.irfft2(np.fft.rfft2(rng.standard_normal((n, n))) * kn, s=(n, n))
            if rho == 0.0:
                blk[i] += (nz * (sp["sigma"] / nz.std())).astype(np.float32)
            else:                                                              # AL3: AR(1) across channels
                e = nz * (sp["sigma"] / nz.std()); cur = e if prev is None else rho * prev + math.sqrt(1 - rho * rho) * e; prev = cur
                blk[i] += cur.astype(np.float32)
        sh.write(blk.astype(">f4"))
    sh.close()
    return C.sha256_file(path)
