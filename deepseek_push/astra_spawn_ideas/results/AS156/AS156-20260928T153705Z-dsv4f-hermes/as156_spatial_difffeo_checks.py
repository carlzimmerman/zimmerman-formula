"""
AS156 - Spatial diffeomorphism generator for heat fields (CA5-GNC-R canonical cell).
Bounded prototype: <=120 s wall, <=512 MB, 1 thread. Exact rational/symbolic arithmetic.

Physics (see derivation.md): the CA4-GNC/CA5-GNC-R action (FINAL_ACTION.md eq (4), pinned hash
b8c04d4e...) contains, besides the metric, carriers phi_A and auxiliaries U, Z, W(r,x), L(r,x),
lambda0(x). NONE of U,Z,W,L,lambda0 carries a time derivative in the action -> primary
constraints pi_U = pi_Z = pi_W(r) = pi_L(r) = pi_lambda0 = 0. The spatial diffeomorphism
generator (extended, before reduction) is

  H_i = -2 D_j pi^j_i + sum_A pi_A D_i phi_A
        + pi_U D_i U + pi_Z D_i Z
        + int_0^b dr [ pi_W(r) D_i W(r) + pi_L(r) D_i L(r) ] + pi_lambda0 D_i lambda0

Checks performed below (all EXACT, actual residual polynomials printed):
  C1  {G(xi), F} = L_xi F for F in {U,Z,W,L,lambda0, phi, their momenta}
  C2  reduction on the auxiliary primary surface = physical constraint (14)
  C3  first-classness: {G(xi), pi_a} weakly zero (stays on primary surface)
  C4  algebra closure: {G(xi), G(eta)} = G([xi,eta]), matter+aux sector (exact, nonlinear)
  C5  NEGATIVE CONTROL: omitting W,L primary terms -> residual -xi.DW != 0 off-shell
  C6  metric sector (2D, 3x3 lattice, exact at linearized level): {G_grav(xi), h_ab} = L_xi h_ab,
      {G_grav(xi), pi^ab} = L_xi pi^ab, gravity-only closure {Gg(xi),Gg(eta)} = Gg([xi,eta])
  C7  dimension/sign/weight audit
"""
import json
import sympy as sp
import time

start = time.time()
RES = {}

# ---------------------------------------------------------------- lattice machinery (1D, N sites)
N = 4
Delta = sp.Rational(1, 2)
mod = lambda s: s % N

def diff1(f, s):
    return (f[mod(s + 1)] - f[mod(s - 1)]) / (2 * Delta)

def lie_scalar(xi, f):
    return [sp.expand(xi[s] * diff1(f, s)) for s in range(N)]

def lie_density(xi, p):
    xp = [sp.expand(xi[s] * p[s]) for s in range(N)]
    return [sp.expand(diff1(xp, s)) for s in range(N)]

# canonical pairs: (name, q-list, p-list) - q weight-0 scalars, p weight-1 densities
phi = [sp.symbols('phi_%d' % s) for s in range(N)]
U = [sp.symbols('U_%d' % s) for s in range(N)]
Z = [sp.symbols('Z_%d' % s) for s in range(N)]
lm = [sp.symbols('lambda_%d' % s) for s in range(N)]
m = 2  # r-slices
W = [[sp.symbols('W%d_%d' % (k, s)) for s in range(N)] for k in range(m)]
L = [[sp.symbols('L%d_%d' % (k, s)) for s in range(N)] for k in range(m)]
ppi = [sp.symbols('ppi_%d' % s) for s in range(N)]
pU = [sp.symbols('pU_%d' % s) for s in range(N)]
pZ = [sp.symbols('pZ_%d' % s) for s in range(N)]
pl = [sp.symbols('pl_%d' % s) for s in range(N)]
pW = [[sp.symbols('pW%d_%d' % (k, s)) for s in range(N)] for k in range(m)]
pL = [[sp.symbols('pL%d_%d' % (k, s)) for s in range(N)] for k in range(m)]

CANON = [('phi', phi, ppi), ('U', U, pU), ('Z', Z, pZ), ('lambda0', lm, pl)]
for k in range(m):
    CANON.append(('W%d' % k, W[k], pW[k]))
    CANON.append(('L%d' % k, L[k], pL[k]))

def bracket(f, g):
    out = sp.Integer(0)
    for name, qs, ps in CANON:
        for s in range(N):
            dfq = sp.diff(f, qs[s]); dgp = sp.diff(g, ps[s])
            dfp = sp.diff(f, ps[s]); dgq = sp.diff(g, qs[s])
            if dfq != 0 and dgp != 0:
                out += dfq * dgp
            if dfp != 0 and dgq != 0:
                out -= dfp * dgq
    return sp.expand(out)

xi = [sp.symbols('xi_%d' % s) for s in range(N)]
eta = [sp.symbols('eta_%d' % s) for s in range(N)]

# ------------------------------------------------------------------ generators (aux sector)
def G_full(xi_v):
    DG = lambda f, s: diff1(f, s)
    G = sp.Integer(0)
    for s in range(N):
        G += xi_v[s] * (ppi[s] * DG(phi, s))
        G += xi_v[s] * (pU[s] * DG(U, s))
        G += xi_v[s] * (pZ[s] * DG(Z, s))
        G += xi_v[s] * (pl[s] * DG(lm, s))
        for k in range(m):
            G += xi_v[s] * (pW[k][s] * DG(W[k], s))
            G += xi_v[s] * (pL[k][s] * DG(L[k], s))
    return sp.expand(G)

def G_cut(xi_v):  # negative control: W,L primary terms omitted; gravity+carrier terms kept symbolically
    DG = lambda f, s: diff1(f, s)
    G = sp.Integer(0)
    for s in range(N):
        G += xi_v[s] * (ppi[s] * DG(phi, s))
        G += xi_v[s] * (pU[s] * DG(U, s))
        G += xi_v[s] * (pZ[s] * DG(Z, s))
        G += xi_v[s] * (pl[s] * DG(lm, s))
    return sp.expand(G)

# the gravity density is the symbolic array Hg (brackets with the metric sector in C6);
# aux/matter brackets with Hg vanish exactly (disjoint variables) - handled implicitly.

# ------------------------------------------------------------------ C1: Lie derivatives on all fields
Gx = G_full(xi)
c1 = {}
for name, qs, ps in CANON:
    for s in range(N):
        # transformation generated by G: delta F = {F, G}  (canonical bracket {q,p} = +delta)
        c1['{ %s_%d, G}-Lxi.%s_%d' % (name, s, name, s)] = sp.expand(bracket(qs[s], Gx) - lie_scalar(xi, qs)[s])
        c1['{ p%s_%d, G}-Lxi.p%s_%d' % (name, s, name, s)] = sp.expand(bracket(ps[s], Gx) - lie_density(xi, ps)[s])
res_c1_nonzero = {k: v for k, v in c1.items() if sp.expand(v) != 0}
RES['C1_lie_derivatives_all_fields'] = {
    'checks': len(c1), 'nonzero_residuals': {k: str(v) for k, v in res_c1_nonzero.items()},
    'pass': len(res_c1_nonzero) == 0,
    'worst': max(c1.items(), key=lambda kv: sp.count_ops(kv[1])) if c1 else None}

