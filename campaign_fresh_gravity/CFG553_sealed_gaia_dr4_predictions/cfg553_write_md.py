#!/usr/bin/env python3
"""CFG553: write PREDICTIONS.md from cfg553_predictions.json (every number in the tables comes from the JSON)."""
import os, json, hashlib

HERE = os.path.dirname(os.path.abspath(__file__))
JP = os.path.join(HERE, "cfg553_predictions.json")
J = json.load(open(JP))
SHA = hashlib.sha256(open(JP, "rb").read()).hexdigest()
FOOTS = ("canonical", "alt")
MODELS = ("RMv", "RMphi", "PD", "NFW")
LAB = {"RMv": "RM-v", "RMphi": "RM-φ", "PD": "PD (QUMOND disc)", "NFW": "NFW (fit to Ou+24)"}
CENSUS = ["B1_s-", "B1_s-/2", "B1_s1", "B1_s+/2", "B1_s+"]
G = J["grids"]
L = []


def w(s=""):
    L.append(s)


def pred(foot, m):
    return J["predictions"]["footing_independent"]["NFW"] if m == "NFW" else J["predictions"][foot][m]


def cell(vals, fmt):
    c = vals[2]; lo, hi = min(vals), max(vals)
    return f"{fmt.format(c)} ({fmt.format(lo)}–{fmt.format(hi)})"


def vec_table(title, getter, rows, rowlab, fmt):
    for foot in FOOTS:
        w(f"**{title} — {foot} footing** (census central (census band); NFW is footing-independent)")
        w()
        w(f"| {rowlab} | " + " | ".join(LAB[m] for m in MODELS) + " |")
        w("|---|" + "---|" * len(MODELS))
        for i, r in enumerate(rows):
            cells = []
            for m in MODELS:
                d = pred(foot, m)
                cells.append(cell([getter(d[v])[i] for v in CENSUS], fmt))
            w(f"| {r:g} | " + " | ".join(cells) + " |")
        w()


w("# CFG553 sealed predictions for Gaia DR4 (release 2026-12-02)")
w()
w(f"Generated by `cfg553_write_md.py` from `cfg553_predictions.json` (SHA-256 `{SHA}`). Criteria: `FROZEN_CRITERIA.md`"
  f" ({J['criteria_commit']}). Sealed before any Gaia DR4 data exist. Never edit after the seal; changes go in a new dated file.")
w()
w("κ = ½ is FITTED; footings a0 = 9.36e-11 (canonical) and 1.13e-10 (alt) m/s², never pooled; ν(y) = 1/(1 − e^(−√y)); no EFE;"
  " McMillan17 census baryons held (A = 1); the band is the census stellar-mass error (stars × 0.895–1.105, gas held)."
  " The cold energy's mass is still required. Not theory closed. These are predictions, not results.")
w()
w("Models: **RM-v / RM-φ** = the round cold-energy rule in its two forms (CFG516); **PD** = the full QUMOND field (phantom disc);"
  " **NFW** = census baryons + NFW fitted to Ou+24 (Gaia DR3), refitted at every baryon value. Galactocentric R with R0 = 8.122 kpc.")
w()
w("## Headline scalars")
w()
for foot in FOOTS:
    B = J["bands"][foot]
    w(f"**{foot} footing** — central (census band) [declared-variant envelope B2/B2b/B3 included]")
    w()
    w("| quantity | " + " | ".join(LAB[m] for m in MODELS) + " |")
    w("|---|" + "---|" * len(MODELS))
    for q in B["RMv"]:
        cells = []
        for m in MODELS:
            b = B[m][q]
            f = "{:.4g}"
            cells.append(f"{f.format(b['central'])} ({f.format(b['lo'])}–{f.format(b['hi'])}) [{f.format(b['env_lo'])}–{f.format(b['env_hi'])}]")
        w(f"| {q} | " + " | ".join(cells) + " |")
    w()
w("Units: K_z/(2πG) and Σ in M☉ pc⁻²; ν_z² in (km/s)² kpc⁻²; V in km/s; ρ in M☉ pc⁻³ or GeV cm⁻³; σ_z in km/s."
  " P3 ρ_dark is the local cold-energy density for RM (spherical), the midplane phantom density for PD, ρ_NFW(R0) for NFW."
  " Σ11_true = ∫ρ_tot dz over |z| < 1.1 kpc; Kz11 = K_z(R0, 1.1)/(2πG) (includes the radial-force term).")
w()
w("## P1 vertical force K_z(R, |z|)/(2πG) [M☉ pc⁻²]")
w()
for iz, z in enumerate(G["P1_z"]):
    vec_table(f"|z| = {z} kpc", lambda o, iz=iz: [row[iz] for row in o["P1"]["Kz_o2piG"]], G["P1_R"], "R [kpc]", "{:.1f}")
w("**Midplane ν_z² ratio PD/RM and K_z(R, 1.1) ratio PD/RM (census central)**")
w()
w("| footing | form | ν_z² PD/RM at R0 | at 16 kpc | K_z,1.1 PD/RM at R = 5 … 16 kpc |")
w("|---|---|---|---|---|")
for foot in FOOTS:
    for f in ("RMv", "RMphi"):
        r = J["disc_round_ratios"][foot][f]
        w(f"| {foot} | {LAB[f]} | {r['nuz2_ratio_R0']:.2f} | {r['nuz2_ratio_PD_over_RM_R16']:.2f} | "
          + " ".join(f"{x:.2f}" for x in r["Kz11_ratio_PD_over_RM_by_R"]) + " |")
w()
w("## P2 rotation curve V_c(R) [km/s]")
w()
vec_table("V_c(R)", lambda o: o["P2"]["Vc"], G["P2_R"], "R [kpc]", "{:.1f}")
w("## P4 σ_z at z = 0 for the declared isothermal tracers [km/s] (tracer-model conditional)")
w()
vec_table("thin tracer h = 0.30 kpc", lambda o: o["P4"]["thin_h0.30"], G["P4_R"], "R [kpc]", "{:.1f}")
vec_table("thick tracer h = 0.90 kpc", lambda o: o["P4"]["thick_h0.90"], G["P4_R"], "R [kpc]", "{:.1f}")
w("## P5 halo-tracer circular speed [km/s]")
w()
vec_table("in-plane V_c (frozen definition)", lambda o: o["P5"]["Vc"], G["P5_R"], "R [kpc]", "{:.1f}")
vec_table("spherical-equivalent √(GM(<r)/r) (added after K6 failed; use when the DR4 analysis quotes M(<r))",
          lambda o: o["P5"]["Vc_sph"], G["P5_R"], "R [kpc]", "{:.1f}")
w("## Separation from the rivals and the DR4 precision needed (3σ)")
w()
w("σ_req(F) = the measurement error at which a framework-central truth excludes the rival's census band at 3σ;"
  " σ_req(R) the reverse. NOT SEP = one central lies inside the other band (not separable at census)."
  " Vector rows: the uniform fractional per-point error f needed (with the declared model floor added); FLOOR-LIMITED ="
  " not reachable even at zero measurement error.")
w()
KEYQ = ["P1_Kz11_R0", "P1_nuz2_R0", "P2_V20", "P2_slope_15_22", "P2_slope_15_27.5", "P3_rho_dark_GeV_cm3",
        "P3_Sigma11_true", "P3_rho_tot_mid", "P4_sigz_thin_R0", "P5_V60", "P5_mean_30_60"]


def fs(x, fmt="{:.3g}"):
    return "NOT SEP" if x is None else fmt.format(x)


def fv(q):
    return "FLOOR-LIMITED" if q["floor_limited"] else f"{100 * q['f_req']:.1f}%"


for foot in FOOTS:
    for form in ("RMv", "RMphi"):
        w(f"**{foot}, {LAB[form]}**")
        w()
        w("| quantity | Δ vs PD | σ_req(F) / σ_req(R) vs PD | Δ vs NFW | σ_req(F) / σ_req(R) vs NFW |")
        w("|---|---|---|---|---|")
        S = J["separations"][foot][form]
        for q in KEYQ:
            a, b = S["PD"][q], S["NFW"][q]
            w(f"| {q} | {a['delta_central']:+.3g} | {fs(a['sigma_req_F_truth'])} / {fs(a['sigma_req_R_truth'])} | "
              f"{b['delta_central']:+.3g} | {fs(b['sigma_req_F_truth'])} / {fs(b['sigma_req_R_truth'])} |")
        for vn in ("P1", "P2", "P4", "P4thick"):
            a, b = S["PD"][f"{vn}_vector"], S["NFW"][f"{vn}_vector"]
            w(f"| {vn} vector (N {a['N']}, floor {a['floor']:.0%}) | — | {fv(a['F_truth'])} / {fv(a['R_truth'])} | — | "
              f"{fv(b['F_truth'])} / {fv(b['R_truth'])} |")
        w()
w("## Decision rules (summary; the frozen text in FROZEN_CRITERIA.md §4–5 governs)")
w()
w("- Scalars: FRAMEWORK-SUPPORTED if the DR4 value is within 2σ of the framework band and ≥ 3σ outside the rival band;"
  " FRAMEWORK-EXCLUDED if the reverse; BOTH EXCLUDED (a framework fail) if ≥ 3σ outside both; otherwise NOT DIAGNOSTIC.")
w("- Vectors: χ² with the analysis covariance plus floors (K_z 5%, V_c 2%, σ_z 5%), minimised over the census band;"
  " consistent p ≥ 0.0455, excluded p < 0.0027; same four labels.")
w("- Per footing × form × rival, never pooled. R0 rescaling, independent distance scales and two tracers must agree,"
  " else NOT DIAGNOSTIC (named).")
w()
w("## Checks (from the JSON)")
w()
for c in J["checks"]:
    w(f"- [{'PASS' if c['ok'] else 'FAIL'}] {c['msg']}")
w()
open(os.path.join(HERE, "PREDICTIONS.md"), "w").write("\n".join(L) + "\n")
print("wrote PREDICTIONS.md;", SHA)
