#!/usr/bin/env python3
"""CFG332 -- writes CFG332_certificate.lean from cfg332_globulars_results.json.  Every input is rounded OUTWARD to 1e-4
(lower ends down, upper ends up) and the decisive scalar claims are stated as rational inequalities proved by norm_num.
It certifies ARITHMETIC on the rounded inputs, not the statistics (the Fisher/chi^2 p-values are not in Lean)."""
import os, json, math
from fractions import Fraction
HERE = os.path.dirname(os.path.abspath(__file__))
R = json.load(open(os.path.join(HERE, "cfg332_globulars_results.json")))
import sys; sys.path.insert(0, os.path.join(HERE, "..", "..", "hunt_2026"))
from hunt_lib import G, Msun, A0  # noqa: E402
PC = 3.0857e16

def lo(x): return Fraction(math.floor(x*1e4), 10000)
def hi(x): return Fraction(math.ceil(x*1e4), 10000)
def q(f): return f"({f.numerator}/{f.denominator} : ℚ)"
T = []
def thm(name, doc, stmt): T.append(f"/-- {doc} -/\ntheorem {name} : {stmt} := by norm_num\n")
key = lambda n: n.replace(" ", "")
cl = {c["name"]: c for c in R["clusters"]}

# Route 1(a): Newtonian prediction / observation at Ups 1.6
for c in R["clusters"]:
    sN = math.sqrt(G*1.6*c["LV"]*Msun/(6*(4/3)*c["rhl"]*PC))/1e3; so = c["so"]
    r = sN/so; L, H = lo(r) - Fraction(1, 1000), hi(r) + Fraction(1, 1000)
    thm(f"r1a_ratio_{key(c['name'])}", f"Route 1(a) owned/Newtonian, Ups 1.6: sigma_N/sigma_obs for {c['name']} lies in [{float(L)}, {float(H)}]",
        f"{q(L)} ≤ {q(lo(sN))} / {q(hi(so))} ∧ {q(hi(sN))} / {q(lo(so))} ≤ {q(H)}")
    if c["name"] == "Pal 3":
        thm("r1a_pal3_needs_ups_above_sps", "Route 1(a): Pal 3 needs a Newtonian M/L_V = 1.6 (sigma_obs/sigma_N)^2 above the SPS ceiling 2.2 (by > 3x)",
            f"(16/10 : ℚ) * ({q(lo(so))} / {q(hi(sN))})^2 > 3 * (22/10 : ℚ)")
# Route 1(b): B's isolated boost exceeds the algebraic-EFE boost
for foot in ("canonical", "alt"):
    for n, d in R["route3"][foot].items():
        if n == "score": continue
        thm(f"r1b_iso_ge_efe_{foot}_{key(n)}", f"Route 1(b-B) vs (b-EFE), {foot}, {n}: isolated boost >= algebraic EFE boost",
            f"{q(lo(d['B_iso']))} ≥ {q(hi(d['B_alg_h93']))}")
# Route 2: MF-slope Ups (branch K, the lower one) vs the framework's required Ups (canonical)
uF = dict(zip([c["name"] for c in R["clusters"]], R["C1"]["canonical"]["uF"]))
for n in ("Pal 4", "Pal 14"):
    u = R["route2"]["ups_mf"]["K"][n][0]
    thm(f"r2_K_exceeds_required_{key(n)}", f"Route 2 branch K: {n}'s MF-depleted stellar M/L ({u:.3f}) is more than twice what the law needs ({uF[n]:.3f}, canonical)",
        f"{q(lo(u))} > 2 * {q(hi(uF[n]))}")
# Route 3: full QUMOND vs algebraic EFE
for foot in ("canonical", "alt"):
    for n in ("Pal 14", "Pal 3", "Pal 4"):
        d = R["route3"][foot][n]
        thm(f"r3_num_ge_alg_{foot}_{key(n)}", f"Route 3, {foot}, {n}: full-QUMOND boost >= algebraic-EFE boost, so sigma_num/sigma_alg >= 1 (computed {d['ratio_sigma']:.4f})",
            f"{q(lo(d['B_num']))} / {q(hi(d['B_alg_h93']))} ≥ 1")
    d = R["route3"][foot]["Pal 14"]; z = hi(1 - d["B_num"]/d["B_iso"]) + Fraction(1, 1000)
    thm(f"r3_pal14_trim_bound_{foot}", f"Route 3, {foot}: the full EFE trims Pal 14's isolated boost by at most {float(z)}",
        f"1 - {q(lo(d['B_num']))} / {q(hi(d['B_iso']))} ≤ {q(z)}")
# Decision rule: every route's T tension exceeds 2 on both footings (T rounded down)
for k, v in R["verdicts"].items():
    thm(f"dec_{k}_not_match", f"Decision: {k} T = {v['T_canonical']:.3f} / {v['T_alt']:.3f} sigma, both > 2 => not MATCH",
        f"{q(lo(v['T_canonical']))} > 2 ∧ {q(lo(v['T_alt']))} > 2")

head = ("import Mathlib\n\n/-!\n# CFG332 -- Lean certificate of the decisive scalars (outer-halo globulars, three routes)\n"
        "Generated by cfg332_lean_gen.py from cfg332_globulars_results.json; inputs rounded OUTWARD to 1e-4.\n"
        "CERTIFIED: rational interval inequalities on those inputs (norm_num). NOT CERTIFIED: the chi^2/Fisher statistics,\n"
        "the QUMOND solve, or any physics; this checks the arithmetic of the claims as stated. Zero sorry.\n-/\n\n")
src = head + "\n".join(T) + f"\n-- theorem count: {len(T)}\n"
open(os.path.join(HERE, "CFG332_certificate.lean"), "w").write(src)
print(f"wrote CFG332_certificate.lean with {len(T)} theorems")
