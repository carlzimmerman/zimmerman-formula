def invert(prof, phit, lo, hi, maxit=300):
    """x with Phi(x) = phit, by safeguarded Newton in s = ln x inside the bracket [lo, hi] (ln x)."""
    phit = np.asarray(phit, float)
    lo = np.array(np.broadcast_to(lo, phit.shape), float)
    hi = np.array(np.broadcast_to(hi, phit.shape), float)
    s = 0.5 * (lo + hi)
    with np.errstate(all='ignore'):
        for _ in range(maxit):
            xx = np.exp(s)
            F = prof.phi(xx) - phit
            pos = F > 0
            hi = np.where(pos, s, hi)
            lo = np.where(pos, lo, s)
            sn = s - F / (xx * prof.g(xx))
            bad = ~((sn >= lo) & (sn <= hi))
            sn = np.where(bad, 0.5 * (lo + hi), sn)
            done = np.all(np.abs(sn - s) <= 2e-15 * np.maximum(1.0, np.abs(s)))
            s = sn
            if done:
                break
    return np.exp(s)


def xmax_of(xe):
    return np.maximum(1e14, 1e8 * np.asarray(xe, float))


def seg_edges(xe, xtop, per_dec):
    n = np.maximum(1, np.ceil(per_dec * np.log10(xtop / xe) - 1e-9).astype(int))
    k = np.arange(n.max() + 1)
    xk = np.minimum(xe[:, None] * 10.0 ** (k[None, :] / per_dec), xtop[:, None])
    xk[:, 0] = xe
    return xk


def t_integral(prof, xe, which, xtop=None, cut=False, chunk=48):
    """Int_0^{t_top} F(E + t^2) dt, F = rho'' ('r2') or drho/dPhi ('d1'), E = Phi(xe), t_top = sqrt(Phi(x_top) - E).
    If not cut and Phi_max is finite, the last piece from x_top to Phi_max is added.  64-node Gauss-Legendre on segments
    ending at xe*10^(k/4); node potentials are formed as Phi_a + (t - t_a)(t + t_a), without cancellation."""
    xe = np.atleast_1d(np.asarray(xe, float))
    out = np.empty(len(xe))
    Ff = prof.r2 if which == 'r2' else prof.d1
    for i0 in range(0, len(xe), chunk):
        x0 = xe[i0:i0 + chunk]
        xt = xmax_of(x0) if xtop is None else np.array(np.broadcast_to(xtop, x0.shape), float)
        xk = seg_edges(x0, xt, 4)
        phik = prof.phi(xk)
        tk = np.sqrt(np.maximum((xk - x0[:, None]) * prof.D(xk, x0[:, None]), 0.0))
        xa, xb = xk[:, :-1], xk[:, 1:]
        ta, tb = tk[:, :-1], tk[:, 1:]
        tsum = ta + tb
        dt = np.where(tsum > 0, (xb - xa) * prof.D(xb, xa) / np.where(tsum > 0, tsum, 1.0), 0.0)
        toff = dt[..., None] * (1 + GLX) / 2
        tau = ta[..., None] + toff
        phin = phik[:, :-1, None] + toff * (tau + ta[..., None])
        lo = np.broadcast_to(np.log(xa)[..., None], tau.shape)
        hi = np.broadcast_to(np.log(xb)[..., None], tau.shape)
        xn = invert(prof, phin, lo, hi)
        val = np.sum(dt[..., None] * (GLW / 2) * Ff(xn), axis=(1, 2))
        if (not cut) and np.isfinite(prof.phimax):
            E = prof.phi(x0)
            pt = prof.phi(xt)
            t1 = np.sqrt((xt - x0) * prof.D(xt, x0))
            t2 = np.sqrt(prof.phimax - E)
            dtl = (prof.phimax - pt) / (t1 + t2)
            toffl = dtl[:, None] * (1 + GLX) / 2
            taul = t1[:, None] + toffl
            phinl = pt[:, None] + toffl * (taul + t1[:, None])
            xnl = invert(prof, phinl, np.broadcast_to(np.log(xt)[:, None], taul.shape),
                         np.full(taul.shape, math.log(1e300)))
            val = val + np.sum(dtl[:, None] * (GLW / 2) * Ff(xnl), axis=1)
        out[i0:i0 + chunk] = val
    return out


def bterm(prof, E):
    """Boundary term of the second form, -(1/(sqrt8 pi^2)) rho'(Phi_max)/sqrt(Phi_max - E); zero for Phi_max = +inf."""
    if not np.isfinite(prof.phimax):
        return np.zeros_like(np.asarray(E, float))
    return -C8 * float(prof.d1_inf) / np.sqrt(prof.phimax - np.asarray(E, float))


def route_A(prof, xe):
    xe = np.atleast_1d(np.asarray(xe, float))
    return C2 * t_integral(prof, xe, 'r2') + bterm(prof, prof.phi(xe))


def local_scale(prof, E):
    s = np.maximum(1.0, np.abs(E))
    s = np.minimum(s, E - prof.phi0)
    return np.minimum(s, prof.phimax - E)


def fd5(prof, xe, fun):
    """5-point central derivative in E of fun(x_E(E)), step 1e-3 s(E)."""
    xe = np.atleast_1d(np.asarray(xe, float))
    E = prof.phi(xe)
    h = 1e-3 * local_scale(prof, E)
    ls = np.log(xe)
    vals = {}
    for m in (-2, -1, 1, 2):
        xm = invert(prof, E + m * h, ls - 2.0, ls + 2.0)
        vals[m] = fun(xm)
    return (vals[-2] - 8 * vals[-1] + 8 * vals[1] - vals[2]) / (12 * h)


def route_C(prof, xe, xtop=None, cut=False):
    return C8 * fd5(prof, xe, lambda xm: 2.0 * t_integral(prof, xm, 'd1', xtop=xtop, cut=cut))


def route_B(prof, xe, absval=False, xtop=None):
    """Second form in x: f = (1/(2 sqrt2 pi^2)) Int_{xe}^{x_top} K(x) dx / sqrt(Phi(x) - E) (+ boundary term)."""
    xe = float(xe)
    xt = float(xmax_of(xe)) if xtop is None else float(xtop)
    Kf = (lambda x: abs(prof.K_s(x))) if absval else prof.K_s
    D = prof.D_s
    tot = 0.0
    with warnings.catch_warnings(record=True) as wl:
        warnings.simplefilter('always', IntegrationWarning)
        b1 = min(2.0 * xe, xt)
        v, _ = quad(lambda x: Kf(x) / math.sqrt(D(x, xe)), xe, b1, weight='alg', wvar=(-0.5, 0.0),
                    epsabs=0.0, epsrel=1e-11, limit=200)
        tot += v
        a = b1
        while a < xt:
            b = min(a * 10 ** 0.5, xt)
            v, _ = quad(lambda x: Kf(x) / math.sqrt((x - xe) * D(x, xe)), a, b, epsabs=0.0, epsrel=1e-11, limit=200)
            tot += v
            a = b
        NWARN['quad'] += sum(1 for w in wl if issubclass(w.category, IntegrationWarning))
    f = tot / (2.0 * SQ2 * PI ** 2)
    if xtop is None and np.isfinite(prof.phimax):
        f += float(bterm(prof, prof.phi_s(xe)))
    return f


def moments_from_f(prof, x, xcut=1e12):
    """rho = 8 sqrt2 pi Int f(Phi+s^2) s^2 ds and rho sigma^2 = (16 sqrt2 pi/3) Int f s^4 ds, f by Route A, 64-node
    Gauss-Legendre in s on half-decade segments of x up to xcut (Phi_max = +inf profiles only)."""
    n = int(np.ceil(2 * np.log10(xcut / x) - 1e-9))
    xk = np.minimum(x * 10.0 ** (np.arange(n + 1) / 2), xcut)
    xk[0] = x
    sk = np.sqrt(np.maximum((xk - x) * prof.D(xk, x), 0.0))
    xa, xb = xk[:-1], xk[1:]
    ds = (xb - xa) * prof.D(xb, xa) / (sk[:-1] + sk[1:])
    soff = ds[:, None] * (1 + GLX) / 2
    s = sk[:-1, None] + soff
    En = prof.phi(xa)[:, None] + soff * (s + sk[:-1, None])
    xEn = invert(prof, En, np.broadcast_to(np.log(xa)[:, None], s.shape), np.broadcast_to(np.log(xb)[:, None], s.shape))
    fn = route_A(prof, xEn.ravel()).reshape(xEn.shape)
    w = ds[:, None] * GLW / 2
    rho = 8 * SQ2 * PI * np.sum(w * fn * s ** 2)
    rs2 = 16 * SQ2 * PI / 3 * np.sum(w * fn * s ** 4)
    return rho, rs2


def f_hernquist(E):
    q2 = -E
    q = math.sqrt(q2)
    br = 3 * math.asin(q) + q * math.sqrt(1 - q2) * (1 - 2 * q2) * (8 * q2 * q2 - 8 * q2 - 3)
    return br / (8 * SQ2 * PI ** 3 * (1 + E) ** 2.5)


def f_kepler(E):
    return 1.0 / (8 * SQ2 * PI ** 3 * np.sqrt(-np.asarray(E, float)))


def f_iso(E):
    return np.exp(-2.0 - 2.0 * np.asarray(E, float)) / PI ** 2.5


def rel(a, b):
    return abs(a / b - 1.0)


def fnum(v):
    if isinstance(v, (bool, np.bool_)):
        return bool(v)
    if isinstance(v, (np.floating, float)):
        return float(v)
    if isinstance(v, (np.integer,)):
        return int(v)
    return v


