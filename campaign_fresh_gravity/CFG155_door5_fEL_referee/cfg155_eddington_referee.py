X = sp.symbols('x', positive=True)


class Profile:
    def __init__(self, name, rho, g, phi, phi0, phimax, D_np, D_s):
        self.name = name
        self.rho_e, self.g_e, self.phi_e = rho, g, phi
        self.phi0, self.phimax = float(phi0), float(phimax)
        self.phi_ok = bool(sp.simplify(sp.diff(phi, X) - g) == 0)
        d1 = sp.simplify(sp.diff(rho, X) / g)
        K = sp.simplify(sp.diff(d1, X))
        r2 = sp.simplify(K / g)
        self.d1_e, self.K_e, self.r2_e = d1, K, r2
        self.d1_inf = sp.limit(d1, X, sp.oo)
        L = lambda e, m: sp.lambdify(X, e, modules=m)
        self.rho, self.g, self.phi = L(rho, 'numpy'), L(g, 'numpy'), L(phi, 'numpy')
        self.d1, self.K, self.r2 = L(d1, 'numpy'), L(K, 'numpy'), L(r2, 'numpy')
        self.K_s, self.phi_s = L(K, 'math'), L(phi, 'math')
        self.mpf = {k: L(e, 'mpmath') for k, e in (('d1', d1), ('K', K), ('r2', r2))}
        self.D, self.D_s = D_np, D_s


def D_tgt_np(x, xe):
    """(Phi(x)-Phi(xe))/(x-xe) for Phi = asinh x - sqrt(1+x^2)/x, via asinh a - asinh b = asinh(a sqrt(1+b^2) - b sqrt(1+a^2))
    and sqrt(1+1/x^2) - sqrt(1+1/xe^2) = -(x-xe)(x+xe)/(x^2 xe^2 (F+Fe))."""
    x = np.asarray(x, float)
    xe = np.asarray(xe, float)
    sx, se = np.sqrt(1 + x * x), np.sqrt(1 + xe * xe)
    den = x * se + xe * sx
    S = (x - xe) * (x + xe) / den
    Ss = np.where(S == 0, 1.0, S)
    ratio = np.where(S == 0, 1.0, np.arcsinh(Ss) / Ss)
    F, Fe = np.sqrt(1 + 1 / (x * x)), np.sqrt(1 + 1 / (xe * xe))
    return ratio * (x + xe) / den + (x + xe) / (x * x * xe * xe * (F + Fe))


def D_tgt_s(x, xe):
    sx, se = math.sqrt(1 + x * x), math.sqrt(1 + xe * xe)
    den = x * se + xe * sx
    S = (x - xe) * (x + xe) / den
    ratio = 1.0 if S == 0 else math.asinh(S) / S
    F, Fe = math.sqrt(1 + 1 / (x * x)), math.sqrt(1 + 1 / (xe * xe))
    return ratio * (x + xe) / den + (x + xe) / (x * x * xe * xe * (F + Fe))


def D_her_np(x, xe):
    return 1.0 / ((1 + np.asarray(x, float)) * (1 + np.asarray(xe, float)))


def D_her_s(x, xe):
    return 1.0 / ((1 + x) * (1 + xe))


def D_sis_np(x, xe):
    x = np.asarray(x, float)
    xe = np.asarray(xe, float)
    u = (x - xe) / xe
    us = np.where(u == 0, 1.0, u)
    return np.where(u == 0, 1.0 / xe, np.log1p(us) / (us * xe))


def D_sis_s(x, xe):
    u = (x - xe) / xe
    return 1.0 / xe if u == 0 else math.log1p(u) / (u * xe)


def build_profiles():
    sq = sp.sqrt(1 + X ** 2)
    tgt = Profile('target', 1 / (4 * sp.pi * X * sq), sq / X ** 2, sp.asinh(X) - sq / X, -np.inf, np.inf,
                  D_tgt_np, D_tgt_s)
    mut = Profile('mutate_cored', 1 / (4 * sp.pi * sp.sqrt(X ** 2 + sp.Rational(1, 100)) * sq), sq / X ** 2,
                  sp.asinh(X) - sq / X, -np.inf, np.inf, D_tgt_np, D_tgt_s)
    her = Profile('hernquist', 1 / (2 * sp.pi * X * (1 + X) ** 3), 1 / (1 + X) ** 2, -1 / (1 + X), -1.0, 0.0,
                  D_her_np, D_her_s)
    sis = Profile('sis', 1 / (4 * sp.pi * X ** 2), 1 / X, sp.log(X), -np.inf, np.inf, D_sis_np, D_sis_s)
    return tgt, mut, her, sis


